CREATE TABLE integration_jobs (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id integer NOT NULL REFERENCES orders (id),
    idempotency_key uuid NOT NULL UNIQUE,
    status text NOT NULL,
    run_at timestamptz NOT NULL,
    locked_at timestamptz NULL,
    lease_token uuid NULL,
    published_at timestamptz NULL,
    publish_locked_at timestamptz NULL,
    correlation_id text NOT NULL,
    CONSTRAINT integration_jobs_status_check
        CHECK (status IN ('queued', 'in_progress', 'done', 'failed', 'cancelled'))
);
CREATE INDEX integration_jobs_status_run_at_idx
    ON integration_jobs (status, run_at);
CREATE INDEX integration_jobs_unpublished_idx
    ON integration_jobs (id)
    WHERE published_at IS NULL AND status != 'cancelled';
CREATE INDEX integration_jobs_publish_pending_idx
    ON integration_jobs (publish_locked_at)
    WHERE published_at IS NULL;
